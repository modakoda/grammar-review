import AppKit
import Carbon.HIToolbox
import CoreGraphics
import GrammarModels

final class PasteController {
    static let shared = PasteController()

    static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private let pasteboard: NSPasteboard
    private var saved: PasteboardSnapshot?
    private var ourChangeCount: Int?
    private var restoreTask: Task<Void, Never>?

    init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    func stage(_ string: String) {
        restoreTask?.cancel()
        restoreTask = nil
        if saved == nil || ourChangeCount != pasteboard.changeCount {
            saved = PasteboardSnapshot.take(from: pasteboard)
        }
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(string, forType: .string)
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.writeObjects([item])
        ourChangeCount = pasteboard.changeCount
    }

    func paste(_ string: String, intoProcess pid: pid_t) -> Bool {
        guard CGPreflightPostEventAccess() else {
            Log.accessibility.error("Paste fallback unavailable: not allowed to post events")
            return false
        }
        stage(string)
        let targetIsFrontmost = NSWorkspace.shared.frontmostApplication?.processIdentifier == pid
        guard Self.postCommandV(to: pid, viaHIDTap: targetIsFrontmost) else {
            restoreNow()
            return false
        }
        return true
    }

    func scheduleRestore(after delay: Duration = .milliseconds(500)) {
        restoreTask?.cancel()
        restoreTask = Task { @MainActor [weak self] in
            try? await Task.sleep(for: delay)
            guard !Task.isCancelled else { return }
            self?.restoreNow()
        }
    }

    func restoreNow() {
        restoreTask?.cancel()
        restoreTask = nil
        defer {
            saved = nil
            ourChangeCount = nil
        }
        guard let saved, pasteboard.changeCount == ourChangeCount else { return }
        saved.restore(to: pasteboard)
    }

    static func postCommandV(to pid: pid_t, viaHIDTap: Bool) -> Bool {
        let source = CGEventSource(stateID: .hidSystemState)
        let key = KeyboardLayout.keyCode(producing: "v") ?? CGKeyCode(kVK_ANSI_V)
        guard let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true),
              let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        else { return false }
        down.flags = .maskCommand
        up.flags = .maskCommand
        if viaHIDTap {
            down.post(tap: .cghidEventTap)
            up.post(tap: .cghidEventTap)
        } else {
            down.postToPid(pid)
            up.postToPid(pid)
        }
        return true
    }
}
